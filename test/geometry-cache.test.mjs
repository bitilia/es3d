import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import { compile } from '../src/pipeline.js';
import { GeometryCache } from '../src/geometry/geometry-cache.js';
import { BENCH_SCENES, benchSceneSource } from '../src/bench/scenes.js';
import { sha256 } from '../src/cache/sha256.js';
import { encodeBundle, decodeBundle } from '../src/cache/mesh-bundle.js';
import { GEOMETRY_REVISION, geometryKey, restoreGeometry, saveGeometry, memoryStore } from '../src/cache/geometry-store.js';

// The persistent geometry cache must give back exactly what generation gives,
// with the same diagnostics, and must never hand one shape's mesh to another.

const EXAMPLES = new URL('../docs/public/examples/', import.meta.url);
const read = (f) => fs.readFileSync(new URL(f, EXAMPLES), 'utf8');

async function documents() {
  const out = fs.readdirSync(EXAMPLES).filter((f) => f.endsWith('.es3d')).sort().map((f) => [f, read(f)]);
  for (const d of BENCH_SCENES) out.push([d.id, await benchSceneSource(d, async (f) => read(f))]);
  // shapes whose generation reports warnings (no example has any)
  out.push(['warnings', '<es3d version="1"><scene><extrude d="M0 0 L4 4 L4 0 L0 4 Z" depth="1"/><path d="M0 0 L1 0 Z M2 2 L5 2 L5 5 Z"/></scene></es3d>']);
  return out;
}

const generateAll = (r) => {
  for (const e of r.scene.geometries) for (let l = 0; l < e.lods; l++) r.cache.mesh(e, l);
};
const sameArray = (a, b) => a.constructor === b.constructor && a.length === b.length && a.every((v, i) => Object.is(v, b[i]));
const geometryReports = (list) => list.filter((d) => d.phase === 'geometry').map((d) => `${d.severity}|${d.code}|${d.message}`).sort();

test('SHA-256 matches node:crypto', () => {
  for (let n = 0; n < 200; n++) {
    const bytes = Uint8Array.from({ length: (n * 13) % 700 }, (_, i) => (i * 7 + n) & 255);
    assert.equal(sha256(bytes), crypto.createHash('sha256').update(bytes).digest('hex'));
  }
  for (const s of ['', 'abc', 'é∑😀'.repeat(30), 'x'.repeat(55), 'x'.repeat(56), 'x'.repeat(64)]) {
    assert.equal(sha256(s), crypto.createHash('sha256').update(s, 'utf8').digest('hex'));
  }
});

test('restored meshes and diagnostics are the generated ones, for every scene', async () => {
  for (const [name, src] of await documents()) {
    const store = memoryStore();
    const a = compile(src, { cache: new GeometryCache() });
    if (!a.scene) continue;
    a.cache.takeDiagnostics();
    generateAll(a);
    const generatedReports = geometryReports(a.cache.takeDiagnostics());
    if (name === 'warnings') assert.ok(generatedReports.length >= 4, 'the warnings document reports warnings');
    const saved = await saveGeometry(a.cache, store);
    const cacheable = a.scene.geometries.filter((e) => e.identity);
    if (!cacheable.length) {
      assert.equal(saved.saved, false, name);
      continue;
    }
    assert.ok(saved.saved, `${name}: ${saved.reason}`);
    // a second save of the same meshes writes nothing
    assert.equal((await saveGeometry(a.cache, store)).reason, 'up to date', name);

    const b = compile(src, { cache: new GeometryCache() });
    b.cache.takeDiagnostics();
    const r = await restoreGeometry(b.cache, store);
    assert.ok(r.hit, `${name}: ${r.reason}`);
    assert.equal(r.key, saved.key, name);
    assert.equal(b.cache.stats.generated, 0, `${name}: nothing generated by restoring`);
    const restoredReports = geometryReports(b.cache.takeDiagnostics());
    for (const [g, e] of a.scene.geometries.entries()) {
      const f = b.scene.geometries[g];
      assert.equal(f.key, e.key);
      for (let l = 0; l < e.lods; l++) {
        if (!e.identity) {
          assert.equal(f.meshes[l], null, `${name}: ${e.key} is not cached`);
          continue;
        }
        const m = f.meshes[l];
        assert.ok(m, `${name} geometry ${g} lod ${l} restored`);
        for (const k of ['positions', 'normals', 'uvs', 'indices']) assert.ok(sameArray(m[k], e.meshes[l][k]), `${name} geometry ${g} lod ${l} ${k}`);
        assert.equal(m.kind, e.meshes[l].kind);
      }
    }
    // the geometry diagnostics of cacheable shapes come back with their meshes
    const fromUncached = geometryReports(a.scene.geometries.filter((e) => !e.identity).flatMap((e) => e.reports.flat().filter(Boolean).map((x) => ({ ...x, phase: 'geometry' }))));
    assert.deepEqual([...restoredReports, ...fromUncached].sort(), generatedReports, `${name}: diagnostics`);
  }
});

test('a damaged or foreign record is not used, and is dropped', async () => {
  const src = read('02-primitives.es3d');
  const store = memoryStore();
  const a = compile(src, { cache: new GeometryCache() });
  generateAll(a);
  const { key } = await saveGeometry(a.cache, store);
  const good = await store.get(key);
  const damage = async (fn) => {
    const copy = good.slice(0);
    fn(new DataView(copy), new Uint8Array(copy));
    await store.put(key, copy);
    const b = compile(src, { cache: new GeometryCache() });
    const r = await restoreGeometry(b.cache, store);
    assert.equal(r.hit, false);
    assert.equal(b.cache.stats.restored, 0);
    assert.equal(await store.get(key), null, 'dropped');
  };
  await damage((v) => v.setUint32(0, 0)); // magic
  await damage((v) => v.setUint32(4, 99, true)); // layout version
  await damage((v, u) => u.fill(0x7b, 12, 20)); // description
  await damage((v) => v.setUint32(8, 1 << 30, true)); // description longer than the record
  // a record cut short
  await store.put(key, good.slice(0, good.byteLength - 8));
  assert.equal((await restoreGeometry(compile(src, { cache: new GeometryCache() }).cache, store)).reason, 'invalid record');
  // a record filed under another name
  const other = await saveGeometry(compile(read('05-gearbox.es3d'), { cache: new GeometryCache() }).cache, store);
  assert.equal(other.reason, 'nothing generated');
  const gear = compile(read('05-gearbox.es3d'), { cache: new GeometryCache() });
  generateAll(gear);
  const g = await saveGeometry(gear.cache, store);
  await store.put(key, await store.get(g.key));
  const b = compile(src, { cache: new GeometryCache() });
  assert.equal((await restoreGeometry(b.cache, store)).reason, 'invalid record');
  assert.equal(decodeBundle(new ArrayBuffer(3)), null);
});

test('record names follow shapes, quality and revision, not order or spelling of unrelated parts', async () => {
  const doc = (d, color = '#c33') => `<es3d version="1"><scene><extrude d="${d}" depth="1" color="${color}"/><sphere radius="2"/></scene></es3d>`;
  const key = async (src, quality = 1, native = true) => {
    const c = new GeometryCache();
    c.quality = quality;
    compile(src, { cache: c });
    return (await geometryKey(c, { native })).key;
  };
  const base = await key(doc('M0 0 L4 0 L4 3 Z'));
  assert.match(base, /^[0-9a-f]{64}$/);
  assert.equal(await key(doc('M0 0 L4 0 L4 3 Z'), 1, false), base, 'Web Crypto and sha256.js agree');
  assert.equal(await key(doc('M0 0 L4 0 L4 3 Z', '#3c3')), base, 'materials do not matter');
  assert.notEqual(await key(doc('M0 0 L4 0 L4 3.0001 Z')), base, 'path data does');
  assert.notEqual(await key(doc('M0 0 L4 0 L4 3 Z'), 0.5), base, 'quality does');
  // the shapes in another order: the same record
  assert.equal(await key(`<es3d version="1"><scene><sphere radius="2"/><extrude d="M0 0 L4 0 L4 3 Z" depth="1"/></scene></es3d>`), base);
  // authored mesh data has no identity
  const c = new GeometryCache();
  compile('<es3d version="1"><scene><mesh positions="0 0 0 1 0 0 0 1 0" indices="0 1 2"/></scene></es3d>', { cache: c });
  assert.equal((await geometryKey(c)).key, null);
});

test('stores keep within their bounds, least recently used first', async () => {
  const store = memoryStore({ maxRecords: 2 });
  const bytes = (n) => new Uint8Array(n).fill(n).buffer;
  await store.put('a', bytes(10));
  await store.put('b', bytes(20));
  await store.get('a');
  await store.put('c', bytes(30));
  assert.equal(store.size, 2);
  assert.equal(await store.get('b'), null);
  assert.equal(new Uint8Array(await store.get('a'))[0], 10);
  const tiny = memoryStore({ maxBytes: 25 });
  await tiny.put('a', bytes(10));
  await tiny.put('b', bytes(20));
  assert.equal(await tiny.get('a'), null);
  // a bundle round-trips through encode/decode on its own
  const decoded = decodeBundle(encodeBundle('k', []));
  assert.equal(decoded.key, 'k');
  assert.equal(decoded.entries.length, 0);
});

// Meshes of every example and benchmark scene, every level. A change to any
// generator changes this digest; then bump GEOMETRY_REVISION (so that caches
// made by earlier versions are not used) and record the new digest here.
const RECORDED = {
  1: '6d0ff7127d16858caedf7351da9e47bbf41c1fcf7494f0bad573068fa9d0fb4e',
};

test('GEOMETRY_REVISION matches what the generators produce', async () => {
  const h = crypto.createHash('sha256');
  for (const [name, src] of await documents()) {
    const r = compile(src, { cache: new GeometryCache() });
    if (!r.scene) continue;
    h.update(name);
    for (const e of r.scene.geometries) {
      h.update(e.key);
      for (let l = 0; l < e.lods; l++) {
        const m = r.cache.mesh(e, l);
        h.update(m.kind);
        for (const a of [m.positions, m.normals, m.uvs, m.indices]) h.update(new Uint8Array(a.buffer, a.byteOffset, a.byteLength));
      }
    }
  }
  const digest = h.digest('hex');
  assert.equal(digest, RECORDED[GEOMETRY_REVISION], `the generators now produce other meshes (digest ${digest}): bump GEOMETRY_REVISION in src/cache/geometry-store.js and record the digest in this test`);
});
