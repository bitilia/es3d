#!/usr/bin/env node
// Compiles the reader's WebAssembly kernels and writes them into
// src/wasm/kernels-binary.js as base64, so the modules need no separate file
// in Node, in Vite builds or in the published package: wasm/*.c into one
// module, and the instance kernel (wasm/simd/*.c) into a second one that
// uses 128-bit SIMD, so a browser without SIMD loses only that kernel.
//
//   npm run wasm            build (needs clang with the wasm32 target and wasm-ld)
//   npm run wasm -- --check exit 1 when the committed module differs from a fresh build
//
// The JavaScript implementations stay the reference: the kernels must give
// the same bits (test/wasm.test.mjs compares them on every example scene).

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'wasm');
const OUT = path.join(ROOT, 'src/wasm/kernels-binary.js');
const clang = process.env.CLANG || 'clang';

const cFiles = (dir) => fs.readdirSync(dir).filter((f) => f.endsWith('.c')).sort().map((f) => path.join(dir, f));
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'es3d-wasm-'));

function build(name, sources, flags) {
  const out = path.join(tmp, `${name}.wasm`);
  execFileSync(clang, [
    '--target=wasm32',
    '-O3',
    '-nostdlib',
    '-ffreestanding',
    // IEEE semantics as in JavaScript: never -ffast-math
    '-ffp-contract=off',
    '-mbulk-memory',
    '-mnontrapping-fptoint',
    ...flags,
    '-Wall',
    '-Wl,--no-entry',
    '-Wl,--strip-all',
    '-Wl,-z,stack-size=65536',
    '-o',
    out,
    ...sources,
  ], { stdio: 'inherit' });
  return fs.readFileSync(out);
}

const kernels = build('kernels', cFiles(SRC), []);
const instances = build('instances', [...cFiles(path.join(SRC, 'simd')), path.join(SRC, 'runtime.c')], ['-msimd128']);
const js = [
  `// Generated by \`npm run wasm\` from wasm/*.c (${kernels.length} bytes) and wasm/simd/*.c (${instances.length} bytes). Do not edit.`,
  `export default '${kernels.toString('base64')}';`,
  `export const INSTANCES = '${instances.toString('base64')}';`,
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== js) {
    console.error('src/wasm/kernels-binary.js is out of date. Run: npm run wasm');
    process.exit(1);
  }
  console.log('src/wasm/kernels-binary.js is up to date');
} else {
  fs.writeFileSync(OUT, js);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${kernels.length} + ${instances.length} bytes of WebAssembly)`);
}
